namespace CombatSolver.FlashBeam;

/// <summary>The K4 reference side: the existing engine's <see cref="SimulationSnapshot"/> read into <see cref="FlashScoreFeatures"/>.</summary>
internal static class FlashScoreProjection
{
    public static FlashScoreFeatures FromSnapshot(SimulationSnapshot snapshot,
        int minimumOutstandingStolenResource = 0) => new()
    {
        Score = snapshot.Score,
        PlayerDead = snapshot.PlayerDead,
        AllEnemiesDead = snapshot.AllEnemiesDead,
        PlayerHp = snapshot.PlayerHp,
        PlayerMaxHp = snapshot.PlayerMaxHp,
        PlayerBlock = snapshot.PlayerBlock,
        OstyHp = snapshot.OstyHp,
        OstyMaxHp = snapshot.OstyMaxHp,
        CumulativePlayerHpLost = snapshot.CumulativePlayerHpLost,
        RecoveredPlayerHp = snapshot.RecoveredPlayerHp,
        DeathSaveHpRestored = snapshot.DeathSaveHpRestored,
        DeathSaveUseCount = snapshot.DeathSaveUseCount,
        ProjectedDeathSaveUseCount = snapshot.ProjectedDeathSaveUseCount,
        ProjectedPlayerHp = snapshot.ProjectedPlayerHp,
        DefensiveBlockValue = snapshot.DefensiveBlockValue,
        LongTermResourceValue = snapshot.LongTermResourceValue,
        GrowthHpCredit = snapshot.GrowthHpCredit,
        AngerCopiesGenerated = snapshot.AngerCopiesGenerated,
        EnemyHp = snapshot.EnemyHp,
        EnemyBlock = snapshot.EnemyBlock,
        RawEnemyHp = snapshot.RawEnemyHp,
        MaxCurrentEnemyHp = snapshot.MaxCurrentEnemyHp,
        AliveEnemyCount = snapshot.AliveEnemyCount,
        AliveEnemyMask = snapshot.AliveEnemyMask,
        RevivingEnemyCount = snapshot.RevivingEnemyCount,
        LiveDeckClutter = snapshot.LiveDeckClutter,
        LiveDeckSize = snapshot.LiveDeckSize,
        OutstandingStolenResource = snapshot.OutstandingStolenResource,
        MinimumOutstandingStolenResource = minimumOutstandingStolenResource,
        RetainedAttackValue = snapshot.RetainedAttackValue,
        FocusTargetCombatId = snapshot.FocusTargetCombatId,
        FocusTargetPressure = snapshot.FocusTargetPressure,
        FocusTargetRemainingHp = snapshot.FocusTargetRemainingHp,
        FocusTargetCurrentThreat = snapshot.FocusTargetCurrentThreat,
        FocusTargetVulnerableTurns = snapshot.FocusTargetVulnerableTurns,
        MostVulnerableTargetCombatId = snapshot.MostVulnerableTargetCombatId,
        EnemyVulnerableTurns = snapshot.EnemyVulnerableTurns,
        Energy = snapshot.Energy,
        Stars = snapshot.Stars,
        HandCount = snapshot.HandCount,
        ReachableHandValue = snapshot.ReachableHandValue,
        ZeroCostPlayableCount = snapshot.ZeroCostPlayableCount,
        PersistentBuffValue = snapshot.PersistentBuffValue,
        StrategicRetentionValue = snapshot.StrategicEffects.RetentionValue,
        Act3BossInteractions = snapshot.Act3BossInteractions,
        FirstAttackDamage = snapshot.FirstAttackDamage,
        EtherealDrawTriggers = snapshot.EtherealDrawTriggers,
        PagestormBonusDrawCapacity = snapshot.PagestormBonusDrawCapacity,
        HighEnergyPlays = snapshot.HighEnergyPlays,
        DemesneEnergyGain = snapshot.DemesneEnergyGain,
        DemesneDrawGain = snapshot.DemesneDrawGain,
        PersistentSetupTraits = snapshot.PersistentSetupTraits,
        StrategicSetupTraits = snapshot.StrategicSetupTraits,
        LatentSetupValue = snapshot.LatentSetupValue,
        FutureResourceValue = snapshot.FutureResourceValue,
        ReplayPotentialValue = snapshot.ReplayPotentialValue,
        DelayedDamageValue = snapshot.DelayedDamageValue,
        ReactiveDamageValue = snapshot.ReactiveDamageValue,
        OffensiveProgressValue = snapshot.OffensiveProgressValue,
        SandpitRemaining = snapshot.SandpitRemaining,
        EnemyStrengthSuppression = snapshot.EnemyStrengthSuppression,
        EnemyWeakTurns = snapshot.EnemyWeakTurns,
        PotionUseCount = snapshot.PotionUseCount,
        PotionStrategicCost = snapshot.PotionStrategicCost,
        AutomaticPotionUseCount = snapshot.AutomaticPotionUseCount,
        ExplicitPotionStrategicCost = snapshot.ExplicitPotionStrategicCost,
        ExplicitPotionUseCount = snapshot.PotionUseCount - snapshot.AutomaticPotionUseCount,
    };
}
